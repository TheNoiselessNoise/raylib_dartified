  final Map<int, XPtr> _rlEnableStatePointer_statePointers = {};

  /// Enable attribute state pointer
  void rlEnableStatePointer(
    int vertexAttribType,
    TypedDataList buffer,
  ) {
    final existing = _rlEnableStatePointer_statePointers[vertexAttribType];
    if (existing != null) existing.free();

    final native = TypedDataList$.Array(buffer, key: 'rlEnableStatePointer_$vertexAttribType');

    _rlEnableStatePointer_statePointers[vertexAttribType] = native;

    _flat.rlEnableStatePointer(
      vertexAttribType,
      native,
    );
  }

  /// Disable attribute state pointer
  void rlDisableStatePointer(int vertexAttribType) {
    _flat.rlDisableStatePointer(vertexAttribType);
    final existing = _rlEnableStatePointer_statePointers.remove(vertexAttribType);
    if (existing != null) existing.free();
  }

