  /// Read texture pixel data
  Uint8List rlReadTexturePixels(
    num id,
    num width,
    num height,
    PixelFormat format,
  ) {
    final size = _coreDart.GetPixelDataSize(
      width.toInt(),
      height.toInt(),
      format,
    );
    final pixelsPtr = _flat.rlReadTexturePixels(
      id.toInt(),
      width.toInt(),
      height.toInt(),
      format.value,
    );
    try {
      return pixelsPtr.asCopy<Uint8List>(size);
    } finally {
      pixelsPtr.free();
    }
  }

  /// Read screen pixel data (color buffer)
  Uint8List rlReadScreenPixels(
    num width,
    num height,
  ) {
    final pixelsPtr = _flat.rlReadScreenPixels(
      width.toInt(),
      height.toInt(),
    );
    try {
      return pixelsPtr.asCopy<Uint8List>(width.toInt()*height.toInt()*4);
    } finally {
      pixelsPtr.free();
    }
  }

