/// A specialised slot-based allocator for C strings ([Pointer\<Char>]).
///
/// Maintains two separate pools:
/// - **Anonymous slots** – a ring buffer of [slotCount] slots, cycled through
///   via [Value] without a key. Useful for transient strings within a single
///   frame.
/// - **Keyed slots** – named slots allocated on demand via [ValueAt] and
///   [Array], persisting until explicitly freed or [_dispose] is called.
///
/// String memory is managed with [malloc] and is grown in-place when the
/// encoded UTF-8 length of a new string exceeds the current slot capacity,
/// avoiding unnecessary reallocations for strings of similar length.
final class RTempStringAlloc extends RTempAlloc<Pointer<Char>> {

  /// Number of anonymous (ring-buffer) string slots pre-reserved on construction.
  final int slotCount;

  RTempStringAlloc(super.temp, super.name, {
    required this.slotCount,
    required super.allocatorFunc,
    required super.printerFunc,
  }) { _reset(); }

  final Map<String, int> _StringSlotsKeyed = {};
  List<Pointer<Char>> _StringSlots = [];
  List<int> _StringCapacities = [];
  int _StringAnonIndex = 0;

  /// Resets all slot bookkeeping structures to their initial state.
  ///
  /// Called during construction and at the end of [_dispose].
  void _reset() {
    // NOTE: needs to be growable
    _StringSlots = .filled(slotCount, nullptr, growable: true);
    _StringCapacities = .filled(slotCount, 0, growable: true);
    _StringAnonIndex = 0;
  }

  /// Allocates and returns an unslotted array of [count] `Pointer<Char>` pointers.
  ///
  /// The caller is responsible for freeing the returned pointer.
  Pointer<Pointer<Char>> Raw([int count = 1]) => allocatorFunc(count);

  /// Writes each string in [array] into keyed sub-slots and returns a tracked
  /// `Pointer<Pointer<Char>>` of length `array.length`.
  ///
  /// Sub-slot keys follow the pattern `'<key>_<i>'`. [key] defaults to
  /// `'default'`.
  Pointer<Pointer<Char>> Array(List<String> array, {String? key}) {
    final arrayKey = _slotKey(key);
    final pp = At(arrayKey, array.length);
    for (int i = 0; i < array.length; i++) pp[i] = ValueAt('${arrayKey}_$i', array[i]);
    return pp;
  }

  /// Fills a tracked [Pointer<Pointer<Char>>] of [count] elements by calling
  /// [init](i) for each index.
  Pointer<Pointer<Char>> Fill(int count, Pointer<Char> Function(int) init, {String? key}) {
    final pp = At(_slotKey(key), count);
    for (int i = 0; i < count; i++) pp[i] = init(i);
    return pp;
  }

  /// Returns a `Pointer<Char>` for [text] using the next anonymous ring-buffer slot.
  /// 
  /// Anonymous slots cycle modulo [slotCount], so older anonymous strings may be overwritten.
  /// 
  /// If [key] is provided, delegates to [ValueAt] instead.
  Pointer<Char> Value(String text, [String? key]) {
    if (key != null) return ValueAt(key, text);
    final slot = _StringAnonIndex;
    _StringAnonIndex = (_StringAnonIndex + 1) % slotCount;
    _ensureStringSlotExists(slot);
    return _writeStringToSlot(slot, text);
  }

  /// Returns the `Pointer<Char>` for the keyed slot [key], optionally writing
  /// [text] into it.
  ///
  /// Allocates the slot on first use. If [text] is `null` the existing string
  /// is returned; asserts that the slot has been initialised at least once.
  Pointer<Char> ValueAt(String key, [String? text]) {
    final slot = _StringSlotsKeyed.putIfAbsent(
      key, () => _StringSlots.length
    );

    _ensureStringSlotExists(slot);

    if (text != null) {
      return _writeStringToSlot(slot, text);
    }

    assert(
      _StringSlots[slot] != nullptr,
      '[TEMP] String.ValueAt("$key") used before initialization'
    );

    return _StringSlots[slot];
  }

  /// Ensures the slot list is large enough to hold index [slot], growing it
  /// with null-pointer sentinels if necessary.
  void _ensureStringSlotExists(int slot) {
    if (slot < _StringSlots.length) return;

    final growBy = slot + 1 - _StringSlots.length;

    _StringSlots.addAll(List.filled(growBy, nullptr));
    _StringCapacities.addAll(List.filled(growBy, 0));
  }

  /// Writes [text] into slot [slot], reallocating if the current capacity is
  /// insufficient for the UTF-8 encoded length.
  ///
  /// Always null-terminates the written string.
  Pointer<Char> _writeStringToSlot(int slot, String text) {
    final encoded = utf8.encode(text);
    final requiredBytes = encoded.length + 1;

    if (
      _StringSlots[slot] == nullptr ||
      _StringCapacities[slot] < requiredBytes
    ) {
      if (_StringSlots[slot] != nullptr) {
        malloc.free(_StringSlots[slot]);
      }

      _StringSlots[slot] = malloc.allocate<Char>(requiredBytes);
      _StringCapacities[slot] = requiredBytes;
    }

    final dst = _StringSlots[slot]
      .cast<Uint8>()
      .asTypedList(requiredBytes);

    dst.setAll(0, encoded);
    dst[encoded.length] = 0;

    return _StringSlots[slot];
  }

  @override
  void Free(String key) {
    if (!_StringSlotsKeyed.containsKey(key)) {
      throw StateError('[FREE] Cannot free unallocated String slot $key');
    }

    int slot = _StringSlotsKeyed[key]!;
    calloc.free(_StringSlots[slot]);
    _StringSlotsKeyed.remove(key);
    _StringSlots.removeAt(slot);
    _StringCapacities.removeAt(slot);
  }

  @override
  void _dispose() {
    if (_StringSlots.isNotEmpty) {
      final nonNulls = _StringSlots.where((e) => e != nullptr);
      _temp.debugFreeInfo('Freeing preallocated $slotCount $name slots (used ${nonNulls.length})');
      nonNulls.forEach(calloc.free);
    }
    if (_StringSlotsKeyed.isNotEmpty) {
      _temp.debugFreeInfo('Freeing user-defined ${_StringSlotsKeyed.length} $name slots');
    }
    _reset();
  }
}

