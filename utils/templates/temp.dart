  void registerAllocator(String key, RTempAlloc alloc) {
    if (_customAllocators.containsKey(key)) {
      final sig = _customAllocators[key]!.signature();
      throw StateError("Allocator '$key' ('$sig') already exists!");
    }

    _customAllocators[key] = alloc;
  }

